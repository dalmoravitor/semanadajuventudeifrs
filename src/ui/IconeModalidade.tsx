import {
  Activity,
  Brain,
  CalendarCheck,
  ChefHat,
  ChessKnight,
  CircleDot,
  ClipboardCheck,
  Disc3,
  Footprints,
  Gamepad2,
  Goal,
  Grid3x3,
  Hand,
  Lasso,
  Mic,
  Package,
  PartyPopper,
  Ruler,
  Spade,
  SpellCheck,
  Swords,
  Target,
  Volleyball,
  type LucideIcon,
} from "lucide-react";

const POR_PREFIXO: [string, LucideIcon][] = [
  ["atletismo", Footprints],
  ["basquetebol", CircleDot],
  ["bisca", Spade],
  ["truco", Spade],
  ["bocha", Disc3],
  ["cabo_de_guerra", Swords],
  ["cs_go", Gamepad2],
  ["fifa", Gamepad2],
  ["mortal_kombat", Gamepad2],
  ["culinaria", ChefHat],
  ["dardo", Target],
  ["disciplina", ClipboardCheck],
  ["futsal", Goal],
  ["gincana_recreativa", PartyPopper],
  ["gincana_tecnico", Brain],
  ["handebol", Hand],
  ["inscricao", Package],
  ["presencas", CalendarCheck],
  ["salto", Ruler],
  ["show", Mic],
  ["soletrando", SpellCheck],
  ["sudoku", Grid3x3],
  ["tiro_laco", Lasso],
  ["volei", Volleyball],
  ["xadrez", ChessKnight],
];

export function IconeModalidade({ id, className }: { id: string; className?: string }) {
  const Icone = POR_PREFIXO.find(([prefixo]) => id.startsWith(prefixo))?.[1] ?? Activity;
  return <Icone aria-hidden className={className ?? "size-5"} strokeWidth={1.75} />;
}
